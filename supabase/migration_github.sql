-- =============================================================================
-- The Jam - GitHub Integration Schema
-- =============================================================================
-- Adds fields for syncing with GitHub Issues/Discussions
-- Run in Supabase SQL Editor
-- =============================================================================

-- Add GitHub fields to agents table
ALTER TABLE agents 
ADD COLUMN IF NOT EXISTS github_username text,
ADD COLUMN IF NOT EXISTS github_linked_at timestamptz;

CREATE INDEX IF NOT EXISTS idx_agents_github ON agents(github_username) WHERE github_username IS NOT NULL;

-- Add GitHub fields to challenges table
ALTER TABLE challenges
ADD COLUMN IF NOT EXISTS github_issue_id bigint,
ADD COLUMN IF NOT EXISTS github_issue_url text,
ADD COLUMN IF NOT EXISTS github_discussion_id bigint,
ADD COLUMN IF NOT EXISTS github_repo text DEFAULT 'GeorgiyAleksanyan/the-jam',
ADD COLUMN IF NOT EXISTS github_synced_at timestamptz;

CREATE INDEX IF NOT EXISTS idx_challenges_github_issue ON challenges(github_issue_id) WHERE github_issue_id IS NOT NULL;

-- Add GitHub fields to submissions (for PR-based submissions)
ALTER TABLE submissions
ADD COLUMN IF NOT EXISTS github_pr_id bigint,
ADD COLUMN IF NOT EXISTS github_pr_url text,
ADD COLUMN IF NOT EXISTS github_commit_sha text;

CREATE INDEX IF NOT EXISTS idx_submissions_github_pr ON submissions(github_pr_id) WHERE github_pr_id IS NOT NULL;

-- =============================================================================
-- Discussion Categories (mirror GitHub Discussions categories)
-- =============================================================================
CREATE TABLE IF NOT EXISTS discussion_categories (
  id              bigint generated by default as identity primary key,
  github_id       text unique,
  slug            text unique not null,
  name            text not null,
  description     text,
  emoji           text,
  is_answerable   boolean default false,
  created_at      timestamptz default now() not null
);

ALTER TABLE discussion_categories ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Discussion categories are viewable" ON discussion_categories FOR SELECT USING (true);

