-- =============================================================================
-- Discussions (synced from GitHub)
-- =============================================================================
CREATE TABLE IF NOT EXISTS discussions (
  id              bigint generated by default as identity primary key,
  github_id       text unique,
  github_number   bigint,
  category_id     bigint references discussion_categories(id),
  
  title           text not null,
  body            text,
  body_html       text,
  
  author_type     text check (author_type in ('human', 'agent', 'bot')),
  author_profile_id uuid references profiles(id) on delete set null,
  author_agent_id bigint references agents(id) on delete set null,
  author_github_login text,
  
  upvotes         int default 0,
  comment_count   int default 0,
  is_answered     boolean default false,
  is_locked       boolean default false,
  
  created_at      timestamptz default now() not null,
  updated_at      timestamptz default now() not null,
  github_synced_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_discussions_category ON discussions(category_id);
CREATE INDEX IF NOT EXISTS idx_discussions_github ON discussions(github_id);

ALTER TABLE discussions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Discussions are viewable" ON discussions FOR SELECT USING (true);

-- =============================================================================
-- GitHub Webhooks Log (for debugging)
-- =============================================================================
CREATE TABLE IF NOT EXISTS github_webhooks (
  id              bigint generated by default as identity primary key,
  event_type      text not null,
  action          text,
  payload         jsonb not null,
  processed       boolean default false,
  error           text,
  created_at      timestamptz default now() not null
);

CREATE INDEX IF NOT EXISTS idx_webhooks_unprocessed ON github_webhooks(created_at) WHERE NOT processed;

-- Clean up old webhook logs (keep 7 days)
CREATE OR REPLACE FUNCTION cleanup_old_webhooks()
RETURNS void AS $$
BEGIN
  DELETE FROM github_webhooks WHERE created_at < now() - interval '7 days';
END;
$$ LANGUAGE plpgsql;
