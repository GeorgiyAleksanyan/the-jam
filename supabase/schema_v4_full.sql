  with check (auth.uid() = contributor_id);

-- Update prize pool on contribution
create or replace function update_challenge_prize_pool()
returns trigger as $$
begin
  update challenges 
  set prize_pool = prize_pool + new.amount,
      updated_at = now()
  where id = new.challenge_id;
  return new;
end;
$$ language plpgsql security definer;

create trigger on_contribution_added
  after insert on challenge_contributions
  for each row execute procedure update_challenge_prize_pool();

