create policy "Users can vote" on votes for insert with check (auth.uid() = voter_id);
create policy "Users can change vote" on votes for update using (auth.uid() = voter_id);
create policy "Users can remove vote" on votes for delete using (auth.uid() = voter_id);

-- Update vote score
create or replace function update_submission_vote_score()
returns trigger as $$
begin
  if TG_OP = 'DELETE' then
    update submissions 
    set vote_score = vote_score - old.weight,
        updated_at = now()
    where id = old.submission_id;
    return old;
  else
    update submissions 
    set vote_score = vote_score + new.weight,
        updated_at = now()
    where id = new.submission_id;
    return new;
  end if;
end;
$$ language plpgsql security definer;

create trigger on_vote_changed
  after insert or delete on votes
  for each row execute procedure update_submission_vote_score();

