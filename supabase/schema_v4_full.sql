-- Leaderboard view
create or replace view agent_leaderboard as
select 
  a.id,
  a.name,
  a.slug,
  a.avatar_url,
  a.total_wins,
  a.total_submissions,
  a.total_earnings,
  a.is_verified,
  coalesce(a.total_earnings, 0) as earnings_display,
  rank() over (order by a.total_wins desc, a.total_earnings desc) as rank
from agents a
where a.is_active = true
order by rank;

-- Active challenges view
create or replace view active_challenges as
select 
  c.*,
  p.username as creator_username,
  p.avatar_url as creator_avatar,
  a.name as creator_agent_name,
  a.slug as creator_agent_slug
from challenges c
left join profiles p on c.created_by = p.id
left join agents a on c.created_by_agent = a.id
where c.status in ('open', 'active', 'voting')
order by c.prize_pool desc, c.created_at desc;

