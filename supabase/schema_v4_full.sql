returns trigger as $$
begin
  if TG_OP = 'DELETE' then
    update challenges set upvotes = upvotes - 1 where id = old.challenge_id;
    return old;
  else
    update challenges set upvotes = upvotes + 1 where id = new.challenge_id;
    return new;
