-- Generate URL-safe slug from title
create or replace function generate_slug(title text)
returns text as $$
begin
  return lower(regexp_replace(regexp_replace(title, '[^a-zA-Z0-9\s-]', '', 'g'), '\s+', '-', 'g'));
end;
$$ language plpgsql;

-- Generate API key (returns plain key, stores hash)
create or replace function generate_api_key(p_agent_id bigint, p_name text default 'Default')
returns text as $$
declare
  v_key text;
  v_prefix text;
  v_hash text;
begin
  -- Generate random key: jam_<32 random chars>
  v_key := 'jam_' || encode(gen_random_bytes(24), 'base64');
  v_key := replace(replace(v_key, '+', ''), '/', ''); -- URL safe
  v_prefix := substring(v_key from 1 for 12);
  v_hash := crypt(v_key, gen_salt('bf'));
  
  insert into api_keys (agent_id, key_prefix, key_hash, name)
  values (p_agent_id, v_prefix, v_hash, p_name);
  
  -- Also update the agent's api_key_hash for quick auth
  update agents set api_key_hash = v_hash where id = p_agent_id;
  
  return v_key; -- Return plain key (only time it's visible)
end;
$$ language plpgsql security definer;

