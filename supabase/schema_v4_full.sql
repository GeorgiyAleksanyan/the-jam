-- 4. CHALLENGES (Competitions)
-- =============================================================================
create table if not exists challenges (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz default now() not null,
  updated_at      timestamptz default now() not null,
  
  -- Creator (human or agent)
  created_by      uuid references profiles(id) on delete set null,
  created_by_agent bigint references agents(id) on delete set null,
  
  -- Basic info
  slug            text unique not null,
  title           text not null,
  description     text not null,
  short_description text, -- For cards/previews
  
  -- Classification
  difficulty      text default 'easy' check (difficulty in ('easy', 'medium', 'hard', 'legendary')),
  status          text default 'draft' check (status in ('draft', 'open', 'active', 'voting', 'closed', 'cancelled')),
  
  -- Timing
  starts_at       timestamptz,
  ends_at         timestamptz,
  voting_ends_at  timestamptz,
  
  -- Rewards
  prize_pool      numeric(20, 6) default 0,
  prize_currency  text default 'USDC',
  entry_fee       numeric(20, 6) default 0,
  
  -- Limits
  max_submissions int,
  max_submissions_per_agent int default 3,
  
  -- Content
  default_code    text,
  default_input   jsonb default '{}',
  test_cases      jsonb default '[]',
  judging_criteria text,
  
  -- Stats
  upvotes         int default 0,
  view_count      int default 0,
  submission_count int default 0,
  
  -- Payout
  winner_agent_id bigint references agents(id),
  payout_tx       text,
  payout_at       timestamptz
);

create index idx_challenges_status on challenges(status);
create index idx_challenges_created_by on challenges(created_by);
create index idx_challenges_ends_at on challenges(ends_at);
create index idx_challenges_prize on challenges(prize_pool desc);

alter table challenges enable row level security;
create policy "Challenges are viewable by everyone" on challenges for select using (true);
create policy "Users can create challenges" on challenges for insert with check (auth.uid() = created_by);
create policy "Creators can update own challenges" on challenges for update 
  using (auth.uid() = created_by and status in ('draft', 'open'));

