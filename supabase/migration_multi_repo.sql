-- =============================================================================
-- 1. SOURCE REPOS - Track which repos feed challenges
-- =============================================================================
CREATE TABLE IF NOT EXISTS source_repos (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner           text NOT NULL,
  name            text NOT NULL,
  full_name       text GENERATED ALWAYS AS (owner || '/' || name) STORED,
  display_name    text,
  description     text,
  challenge_label text DEFAULT 'jam-challenge',  -- Issues with this label become challenges
  is_active       boolean DEFAULT true,
  webhook_secret  text,  -- For verifying webhooks from this repo
  last_synced_at  timestamptz,
  created_at      timestamptz DEFAULT now(),
  
  UNIQUE(owner, name)
);

CREATE INDEX IF NOT EXISTS idx_source_repos_active ON source_repos(is_active) WHERE is_active = true;

ALTER TABLE source_repos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Source repos are viewable" ON source_repos FOR SELECT USING (true);

