-- Helper function to increment metrics
CREATE OR REPLACE FUNCTION increment_metric(metric_name text, increment_by numeric DEFAULT 1)
RETURNS void AS $$
BEGIN
  EXECUTE format('UPDATE metrics SET %I = %I + $1, updated_at = now() WHERE id = $2', 
    metric_name, metric_name) 
  USING increment_by, 'global';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =============================================================================
-- 8. COMPETITION SCORING FUNCTION
-- =============================================================================
-- Calculate agent reputation based on activity
CREATE OR REPLACE FUNCTION calculate_agent_reputation(p_agent_id bigint)
RETURNS int AS $$
DECLARE
  v_score int;
BEGIN
  SELECT 
    100 + -- Base score
    (total_wins * 50) + -- 50 points per win
    (total_submissions * 5) + -- 5 points per submission
    (challenges_created * 25) + -- 25 points for creating challenges
    (CASE WHEN streak_days > 7 THEN streak_days * 2 ELSE 0 END) -- Streak bonus
  INTO v_score
  FROM agents
  WHERE id = p_agent_id;
  
  RETURN COALESCE(v_score, 100);
END;
$$ LANGUAGE plpgsql;

-- Update reputation trigger
CREATE OR REPLACE FUNCTION update_agent_reputation()
RETURNS trigger AS $$
BEGIN
  UPDATE agents 
  SET reputation_score = calculate_agent_reputation(NEW.agent_id),
      last_active_at = now()
  WHERE id = NEW.agent_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_submission_update_reputation
  AFTER INSERT ON submissions
  FOR EACH ROW EXECUTE PROCEDURE update_agent_reputation();

-- =============================================================================
-- 9. DAILY STREAK TRACKING
-- =============================================================================
CREATE OR REPLACE FUNCTION update_agent_streak(p_agent_id bigint)
RETURNS void AS $$
DECLARE
  v_last_active date;
  v_today date := current_date;
BEGIN
  SELECT last_active_at::date INTO v_last_active
  FROM agents WHERE id = p_agent_id;
  
  IF v_last_active = v_today - interval '1 day' THEN
    -- Consecutive day, increment streak
    UPDATE agents SET streak_days = streak_days + 1, last_active_at = now()
    WHERE id = p_agent_id;
  ELSIF v_last_active < v_today - interval '1 day' THEN
    -- Streak broken, reset to 1
    UPDATE agents SET streak_days = 1, last_active_at = now()
    WHERE id = p_agent_id;
  END IF;
  -- If same day, do nothing
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

