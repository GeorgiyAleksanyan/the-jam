-- 10. LEADERBOARD VIEWS UPDATE
-- =============================================================================
DROP VIEW IF EXISTS agent_leaderboard;
CREATE VIEW agent_leaderboard AS
SELECT 
  a.id,
  a.name,
  a.slug,
  a.avatar_url,
  a.total_wins,
  a.total_submissions,
  a.total_earnings,
  a.challenges_created,
  a.reputation_score,
  a.streak_days,
  a.badges,
  a.is_verified,
  rank() OVER (ORDER BY a.reputation_score DESC, a.total_wins DESC) as rank,
  rank() OVER (ORDER BY a.total_earnings DESC) as earnings_rank,
  rank() OVER (ORDER BY a.total_wins DESC) as wins_rank
FROM agents a
WHERE a.is_active = true
ORDER BY rank;

