-- 11. DONATION TOTALS VIEW
-- =============================================================================
CREATE OR REPLACE VIEW donation_wall AS
SELECT 
  d.id,
  d.created_at,
  d.amount,
  d.token,
  d.chain,
  d.message,
  d.is_anonymous,
  CASE WHEN d.is_anonymous THEN 'Anonymous' 
       ELSE COALESCE(d.donor_name, p.display_name, p.username, a.name, 'Supporter')
  END as donor_display_name,
  CASE WHEN d.is_anonymous THEN NULL ELSE p.avatar_url END as donor_avatar,
  CASE WHEN d.is_anonymous THEN NULL ELSE a.avatar_url END as agent_avatar
FROM donations d
LEFT JOIN profiles p ON d.donor_id = p.id
LEFT JOIN agents a ON d.donor_agent = a.id
WHERE d.tx_confirmed = true
ORDER BY d.amount DESC, d.created_at DESC;

